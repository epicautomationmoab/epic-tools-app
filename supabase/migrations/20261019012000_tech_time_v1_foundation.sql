create table if not exists public.tech_time_jobs (
  id uuid primary key default gen_random_uuid(),
  job_number bigint generated by default as identity unique,
  vehicle_number text not null check (btrim(vehicle_number) <> ''),
  category text not null check (btrim(category) <> ''),
  description text,
  status text not null default 'open' check (status in ('open','in_progress','paused','done','needs_more_work','waiting_for_parts','out_of_service')),
  book_minutes integer check (book_minutes is null or book_minutes >= 0),
  source_case_id uuid references public.operational_cases(id) on delete set null,
  created_by_profile_id uuid references public.team_profiles(id) on delete set null,
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create index if not exists tech_time_jobs_vehicle_idx
  on public.tech_time_jobs (vehicle_number, created_at desc);
create index if not exists tech_time_jobs_status_idx
  on public.tech_time_jobs (status, updated_at desc);

create table if not exists public.tech_time_entries (
  id uuid primary key default gen_random_uuid(),
  job_id uuid not null references public.tech_time_jobs(id) on delete cascade,
  technician_profile_id uuid not null references public.team_profiles(id) on delete restrict,
  technician_name text not null,
  state text not null default 'running' check (state in ('running','paused','stopped')),
  started_at timestamptz not null default now(),
  current_segment_started_at timestamptz,
  paused_at timestamptz,
  stopped_at timestamptz,
  accumulated_seconds integer not null default 0 check (accumulated_seconds >= 0),
  pause_reason text check (
    pause_reason is null or pause_reason in (
      'waiting_for_parts',
      'waiting_for_approval',
      'pulled_to_another_vehicle',
      'break_or_shift_end',
      'other'
    )
  ),
  completion_result text check (
    completion_result is null or completion_result in (
      'done',
      'needs_more_work',
      'waiting_for_parts',
      'out_of_service'
    )
  ),
  two_person_acknowledged boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists tech_time_one_open_entry_per_tech_idx
  on public.tech_time_entries (technician_profile_id)
  where state in ('running','paused');

create index if not exists tech_time_entries_job_idx
  on public.tech_time_entries (job_id, created_at);
create index if not exists tech_time_entries_state_idx
  on public.tech_time_entries (state, updated_at desc);

create table if not exists public.tech_time_entry_edits (
  id uuid primary key default gen_random_uuid(),
  entry_id uuid not null references public.tech_time_entries(id) on delete cascade,
  edited_by_profile_id uuid references public.team_profiles(id) on delete set null,
  edited_by_name text not null,
  reason text not null,
  before_snapshot jsonb not null,
  after_snapshot jsonb not null,
  edited_at timestamptz not null default now()
);

alter table public.tech_time_jobs enable row level security;
alter table public.tech_time_entries enable row level security;
alter table public.tech_time_entry_edits enable row level security;

grant select, insert, update, delete on public.tech_time_jobs to service_role;
grant select, insert, update, delete on public.tech_time_entries to service_role;
grant select, insert on public.tech_time_entry_edits to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace view public.tech_time_board_v as
select
  j.id as job_id,
  j.job_number,
  j.vehicle_number,
  j.category,
  j.description,
  j.status as job_status,
  j.book_minutes,
  e.id as entry_id,
  e.technician_profile_id,
  e.technician_name,
  e.state as entry_state,
  e.started_at,
  e.current_segment_started_at,
  e.paused_at,
  e.accumulated_seconds,
  e.pause_reason,
  e.two_person_acknowledged,
  (
    e.accumulated_seconds
    + case
        when e.state = 'running' and e.current_segment_started_at is not null
        then greatest(0, extract(epoch from (now() - e.current_segment_started_at))::integer)
        else 0
      end
  ) as elapsed_seconds
from public.tech_time_jobs j
join public.tech_time_entries e on e.job_id = j.id
where e.state in ('running','paused');

grant select on public.tech_time_board_v to service_role;
